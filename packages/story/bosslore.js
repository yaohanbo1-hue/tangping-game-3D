// ─── 3. 运行时 ─────────────────────────────────────────────
const BossLore = {
  /** @type {Object<string, Set<number>>} 本局已播过台词的 BOSS 阶段（避免同局重复播） */
  _said: null,

  init() { if (!this._said) this._said = {}; },

  /** 取某个 BOSS 的档案；不存在返回 null */
  profile(key) { return BOSS_PROFILES[key] || null; },

  /** 全部 BOSS 档案（按波次排序），供图鉴展示 */
  list() {
    return Object.keys(BOSS_PROFILES)
      .map(k => BOSS_PROFILES[k])
      .sort((a, b) => a.wave - b.wave);
  },

  /**
   * 取某个 BOSS 某阶段的台词（随机一条）。
   * 同局内同一阶段只播一次 —— BOSS 反复进出阶段时不该重复刷屏。
   * @param {string} key   - BOSS 键（abyss / machine / void / lord / final）
   * @param {number} phase - 阶段号（1 / 2 / 3）
   * @returns {string|null}
   */
  say(key, phase) {
    this.init();
    const pool = (BOSS_PHASE_LINES[key] || {})[phase];
    if (!pool || !pool.length) return null;
    if (!this._said[key]) this._said[key] = new Set();
    if (this._said[key].has(phase)) return null;
    this._said[key].add(phase);
    return pool[Math.floor(Math.random() * pool.length)];
  },

  /** 击败独白（优先用本文件的 defeat，回退到 story.js BOSS_DIALOG 的 defeat） */
  defeatLine(key) {
    const p = BOSS_PROFILES[key];
    if (p && p.defeat) return p.defeat;
    if (typeof BOSS_DIALOG !== 'undefined' && BOSS_DIALOG[key]) return BOSS_DIALOG[key].defeat || null;
    return null;
  },

  /** 开新局清空「已播台词」记录 */
  reset() { this._said = {}; },
};

