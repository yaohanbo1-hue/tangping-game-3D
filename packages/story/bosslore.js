//    lore.js       —— 平行：BOSS 的来历与世界观词条互相引用（profile.loreRef）
//    chapters.js   —— 配合：BOSS 波次同时也是幕内关键节点
//    core.js       —— 触发：e.phase 变化时调 BossLore.say(bossKey, phase)
//    main.js       —— 展示：图鉴面板新增「阶段首领档案」章节
//
//  设计原则：每个 BOSS 都必须能回答一个问题 —— 「它曾经是什么？」
//    它们不是外来的怪物，是这场梦里某样东西长出的形状。
//    答案越具体，玩家越难把它们当成纯粹的数值。
// ============================================================

