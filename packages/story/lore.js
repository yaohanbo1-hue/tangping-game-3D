// ─── 4. 运行时：词条解锁与查询 ─────────────────────────────
// 设计约束：与 DreamFragments 保持同一套「_unlocked 集合 + 存档存取」的形态，
// 方便 save.js 用同样的方式接进 captureDream / restoreDream。
const LoreCodex = {
  /** @type {Set<string>} 已解锁词条 id */
  _unlocked: null,

  init() {
    if (!this._unlocked) this._unlocked = new Set();
    // 初始可见词条（unlock === null）直接给
    LORE_ENTRIES.forEach(e => { if (!e.unlock) this._unlocked.add(e.id); });
  },

  /**
   * 解锁单个词条
   * @param {string} id - LORE_ENTRIES 的 id
   * @param {boolean} [silent] - 为 true 时不发提示（批量补解锁用）
   * @returns {object|null} 解锁成功的词条定义；已解锁或不存在返回 null
   */
  unlock(id, silent) {
    this.init();
    if (!id || this._unlocked.has(id)) return null;
    const entry = LORE_ENTRIES.find(e => e.id === id);
    if (!entry) return null;
    this._unlocked.add(id);
    if (!silent) {
      // 走宿主接口（见 host.js）。全局探测在 ESM 里恒失效 —— 会静默不提示。
      getStoryHost().toast(entry.icon + ' 解锁设定', entry.title + ' — ' + entry.brief, 'gold');
    }
    return entry;
  },

  /** 按波次批量解锁（由 DreamEngine.onWaveStart 调用） */
  unlockByWave(wave) {
    this.init();
    const got = [];
    LORE_ENTRIES.forEach(e => {
      if (e.unlock && e.unlock.wave && wave >= e.unlock.wave) {
        const r = this.unlock(e.id, true);
        if (r) got.push(r);
      }
    });
    if (got.length) {
      // 一次解锁多条时合并成一条提示，避免刷屏
      const titles = got.map(g => g.icon + g.title).join(' · ');
      getStoryHost().toast('📘 设定更新 +' + got.length, titles, 'gold');
    }
    return got;
  },

  isUnlocked(id) { this.init(); return this._unlocked.has(id); },

  /** 取某个分类下的全部词条，附带解锁状态 */
  byCategory(catId) {
    this.init();
    return LORE_ENTRIES.filter(e => e.cat === catId).map(e => ({
      def: e, unlocked: this._unlocked.has(e.id),
    }));
  },

  /** 全部词条（带解锁状态） */
  all() {
    this.init();
    return LORE_ENTRIES.map(e => ({ def: e, unlocked: this._unlocked.has(e.id) }));
  },

  /** 解锁进度：{ unlocked, total, percent } */
  progress() {
    this.init();
    const total = LORE_ENTRIES.length;
    const unlocked = this._unlocked.size;
    return { unlocked, total, percent: total ? Math.round(unlocked / total * 100) : 0 };
  },

  /** 存档用：导出为数组 */
  snapshot() { this.init(); return Array.from(this._unlocked); },

  /** 存档用：从数组恢复（与已有进度取并集，不回退） */
  restore(arr) {
    this.init();
    if (Array.isArray(arr)) arr.forEach(id => this._unlocked.add(id));
  },
};

